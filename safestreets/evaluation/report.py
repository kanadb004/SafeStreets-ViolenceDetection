"""Renders `docs/RESULTS.md` from committed `artifacts/reports/eval_*.json` and
`artifacts/reports/cross_dataset.json`. Deterministic and idempotent: same
inputs always render the same bytes, so `docs/RESULTS.md` is **generated**,
never hand-typed, and a second run against unchanged artefacts produces an
empty `git diff` (docs/SPRINT_PLAN.md Sprint 2 DoD).
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

_METRIC_ORDER = ("roc_auc", "pr_auc", "accuracy", "precision", "recall", "f1")
_METRIC_LABELS = {
    "roc_auc": "ROC-AUC",
    "pr_auc": "PR-AUC",
    "accuracy": "Accuracy",
    "precision": "Precision",
    "recall": "Recall",
    "f1": "F1",
}


def _load_json(path: Path | str) -> dict:
    with open(path) as f:
        return json.load(f)


def _fmt(value: float) -> str:
    if value != value:  # NaN
        return "n/a"
    return f"{value:.4f}"


def _metrics_table(eval_report: dict) -> str:
    lines = ["| Metric | Value | 95% CI |", "|---|---|---|"]
    for key in _METRIC_ORDER:
        entry = eval_report[key]
        lo, hi = entry["ci95"]
        lines.append(
            f"| {_METRIC_LABELS[key]} | {_fmt(entry['value'])} | [{_fmt(lo)}, {_fmt(hi)}] |"
        )
    cm = eval_report["confusion_matrix"]
    lines.append("")
    lines.append(
        f"Confusion matrix (n={eval_report['n']}, threshold={eval_report['threshold']:.4f}):"
    )
    lines.append("")
    lines.append("| | pred 0 | pred 1 |")
    lines.append("|---|---|---|")
    lines.append(f"| true 0 | {cm['tn']} | {cm['fp']} |")
    lines.append(f"| true 1 | {cm['fn']} | {cm['tp']} |")
    return "\n".join(lines)


def _cross_dataset_table(cross_dataset: dict) -> str:
    lines = [
        "| Test dataset | In-domain? | n | ROC-AUC | 95% CI | AUC drop vs. in-domain |",
        "|---|---|---|---|---|---|",
    ]
    for row in cross_dataset["rows"]:
        lo, hi = row["roc_auc_ci95"]
        drop = row["auc_drop_vs_in_domain"]
        drop_str = "-" if drop is None else f"{drop:+.4f}"
        lines.append(
            f"| {row['test_dataset']} | {'yes' if row['in_domain'] else 'no (zero-shot)'} "
            f"| {row['n']} | {_fmt(row['roc_auc'])} | [{_fmt(lo)}, {_fmt(hi)}] | {drop_str} |"
        )
    return "\n".join(lines)


def _tuning_section(eval_test: dict, eval_test_tuned: dict | None) -> list[str]:
    """Sprint 3: the tuned winner beside the baseline, both at the baseline's
    F1-optimal threshold so the rows are directly comparable. Present only
    when `artifacts/reports/eval_test_tuned.json` exists (Sprint 3 has run).
    """
    if eval_test_tuned is None:
        return []
    lines = [
        "## HPO-tuned model vs. baseline",
        "",
        "Both rows scored on the same combined test split, at the baseline's F1-optimal"
        " threshold. See `docs/decisions/ADR-004-hpo.md` for the search and"
        " `artifacts/figures/optuna_{history,importances}.png` for the study.",
        "",
        "| Model | ROC-AUC | 95% CI | Accuracy | F1 |",
        "|---|---|---|---|---|",
    ]
    rows = (("Baseline (lstm_head)", eval_test), ("Tuned (lstm_head_tuned)", eval_test_tuned))
    for label, report in rows:
        lo, hi = report["roc_auc"]["ci95"]
        lines.append(
            f"| {label} | {_fmt(report['roc_auc']['value'])} | [{_fmt(lo)}, {_fmt(hi)}] "
            f"| {_fmt(report['accuracy']['value'])} | {_fmt(report['f1']['value'])} |"
        )
    baseline_auc = eval_test["roc_auc"]["value"]
    tuned_auc = eval_test_tuned["roc_auc"]["value"]
    verdict = (
        "the tuned model beats the baseline and ships."
        if tuned_auc > baseline_auc
        else "tuning did not beat the baseline; the baseline ships, reported here as-is."
    )
    lines.append("")
    lines.append(f"{verdict}")
    lines.append("")
    return lines


def render_results_md(
    eval_val: dict,
    eval_test: dict,
    cross_dataset: dict,
    infer_cfg: dict,
    train_datasets: list[str],
    eval_test_tuned: dict | None = None,
) -> str:
    sel = eval_val["selection"]
    f1_t = sel["f1_optimal"]["threshold"]
    rf_t = sel["recall_floor"]["threshold"]
    rf_floor = sel["recall_floor"]["floor"]

    if abs(infer_cfg["threshold"] - f1_t) > 1e-9:
        raise ValueError(
            f"configs/infer.yaml threshold {infer_cfg['threshold']} disagrees with "
            f"eval_val.json's f1_optimal threshold {f1_t}; regenerate both together."
        )

    parts = [
        "# SafeStreets — Evaluation Results",
        "",
        "**Generated by `scripts/evaluate.py` + `safestreets.evaluation.report`."
        " Do not hand-edit; every number here traces to a committed"
        " `artifacts/reports/eval_*.json`.**",
        "",
        "Model: `lstm_head` (ADR-003), trained on "
        + " + ".join(train_datasets)
        + " (`configs/train.yaml`).",
        "",
        "## Threshold selection (validation only)",
        "",
        f"Both operating points below are selected on the **validation** split"
        f" ({' + '.join(train_datasets)} val); test is touched only for the"
        f" headline numbers further down.",
        "",
        f"- F1-optimal threshold: **{f1_t:.4f}**"
        f" (F1={_fmt(sel['f1_optimal']['metrics']['f1']['value'])} on val)."
        f" Persisted to `configs/infer.yaml` as the active threshold.",
        f"- Recall >= {rf_floor:.2f} threshold (the deployment-relevant point for a"
        f" safety system): **{rf_t:.4f}**"
        f" (recall={_fmt(sel['recall_floor']['metrics']['recall']['value'])},"
        f" precision={_fmt(sel['recall_floor']['metrics']['precision']['value'])} on val).",
        "",
        "![Validation threshold sweep](../artifacts/figures/threshold_sweep.png)",
        "",
        "## Headline test metrics",
        "",
        "In-domain test split is RLVS test + AIRTLab test + UCF-Crime test combined"
        " (RWF-2000 contributes no test rows under its official split, ADR-002)."
        f" Evaluated at the F1-optimal threshold ({f1_t:.4f}).",
        "",
        _metrics_table(eval_test),
        "",
        "![ROC curve](../artifacts/figures/roc.png)",
        "",
        "![Precision-recall curve](../artifacts/figures/pr.png)",
        "",
        "![Confusion matrix](../artifacts/figures/confusion.png)",
        "",
        "## Cross-dataset generalisation",
        "",
        "Model trained on " + " + ".join(cross_dataset["train_datasets"]) + " only."
        " RLVS test is in-domain (held out of training, same source distribution);"
        " AIRTLab and UCF-Crime are zero-shot: the model never saw either during training.",
        "",
        _cross_dataset_table(cross_dataset),
        "",
        *_tuning_section(eval_test, eval_test_tuned),
        "## Limitations",
        "",
        "- **Frame-level AUC on untrimmed video is out of scope.** XD-Violence was never"
        " fetched (38.3 GB, over the disk budget, ADR-002) and the UCF-Crime subset holds"
        " only 35 clips total, too few for a meaningful frame-level AUC. See"
        " docs/SPRINT_PLAN.md §2.",
        "- **AIRTLab is acted, staged footage**, not organic violence. Its cross-dataset"
        " AUC above reflects generalisation to a different *filming style* for the same"
        " staged-violence task, not to real-world unscripted footage; read the AIRTLab row"
        " with that caveat, including in any fine-tuning done on it later.",
        "- The UCF-Crime test split is 5 clips (1 negative, 4 positive); its row above"
        " carries a wide or undefined bootstrap CI purely from sample size, not a modelling"
        " claim.",
        "",
    ]
    return "\n".join(parts) + "\n"


def generate(
    reports_dir: Path | str = "artifacts/reports",
    infer_yaml_path: Path | str = "configs/infer.yaml",
    out_path: Path | str = "docs/RESULTS.md",
    train_datasets: list[str] | None = None,
) -> str:
    reports_dir = Path(reports_dir)
    eval_val = _load_json(reports_dir / "eval_val.json")
    eval_test = _load_json(reports_dir / "eval_test.json")
    cross_dataset = _load_json(reports_dir / "cross_dataset.json")
    with open(infer_yaml_path) as f:
        infer_cfg = yaml.safe_load(f)

    tuned_path = reports_dir / "eval_test_tuned.json"
    eval_test_tuned = _load_json(tuned_path) if tuned_path.exists() else None

    text = render_results_md(
        eval_val,
        eval_test,
        cross_dataset,
        infer_cfg,
        train_datasets or ["rwf2000", "rlvs"],
        eval_test_tuned=eval_test_tuned,
    )
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(text)
    return text
